import assert from 'node:assert/strict';
import { EMPTY_SETTINGS, STARTER_SETTINGS, initialSettings, routingReadiness, selectModel, validateSettings } from '../lib/model-routing.mjs';
const original = JSON.stringify(EMPTY_SETTINGS);
const first = initialSettings(EMPTY_SETTINGS);
assert.equal(first.setup_version, 1);
assert.deepEqual(first.allowedModels, ['openrouter/free']);
assert.equal(selectModel(first, 'customer', '示例防弹衣 A多少钱').model, 'openrouter/free');
assert.equal(selectModel(first, 'staff', '对比一下').model, 'openrouter/free');
assert.equal(JSON.stringify(EMPTY_SETTINGS), original);
assert.deepEqual(initialSettings(first), first);
const custom = validateSettings({ allowedModels: ['example/model'], staff: { mode: 'manual', defaultModel: 'example/model' }, customer: { mode: 'auto', simpleModel: 'example/model', complexModel: 'example/model' } });
assert.deepEqual(initialSettings(custom), { ...custom, setup_version: 1 });
const deliberatelyDisabled = { ...structuredClone(EMPTY_SETTINGS), setup_version: 1 };
assert.deepEqual(initialSettings(deliberatelyDisabled), deliberatelyDisabled);
assert.equal(routingReadiness(deliberatelyDisabled, 'customer').ready, false);
const incomplete = structuredClone(STARTER_SETTINGS);
incomplete.customer = { mode: 'auto', defaultModel: '', simpleModel: 'openrouter/free', complexModel: '' };
assert.equal(routingReadiness(incomplete, 'customer').ready, false);
assert.equal(routingReadiness(STARTER_SETTINGS, 'customer').ready, true);
assert.throws(() => selectModel(STARTER_SETTINGS, 'customer', '价格', 'openrouter/free'), /MODEL_OVERRIDE_FORBIDDEN/);
console.log('PASS: first-time free defaults, custom settings preservation, explicit disable preservation, complete B/C routing, and customer override restrictions; no provider requests.');